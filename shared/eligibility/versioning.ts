// Templates
// ---------------------------------------------------------------------------------------------

/** A shared baseline (for example one sponsor's rules used by many sites), keyed "name@year". */
export interface RuleSetTemplate {
  readonly key: string;
  readonly coverage: Readonly<Partial<Record<EligibilityDimension, Coverage>>>;
  readonly rules: readonly EligibilityRule[];
  readonly anyOf: EligibilityRuleSet["anyOf"];
  readonly attestations: readonly Attestation[];
}

function overrideById<T extends { id: string }>(base: readonly T[], own: readonly T[]): T[] {
  const ownIds = new Set(own.map((x) => x.id));
  return [...base.filter((x) => !ownIds.has(x.id)), ...own];
}

/** Explicit review outranks an implicit state when a template and a site disagree. */
const COVERAGE_STRENGTH: Record<Coverage, number> = { not_reviewed: 0, none_stated: 1, no_restriction: 2, encoded: 2 };

function mergeCoverage(template: RuleSetTemplate["coverage"], own: EligibilityRuleSet["coverage"]): EligibilityRuleSet["coverage"] {
  const out: Partial<Record<EligibilityDimension, Coverage>> = { ...template };
  for (const [dim, state] of Object.entries(own) as [EligibilityDimension, Coverage][]) {
    const base = template[dim];
    // The site's explicit choice wins (encoded or no_restriction, even if broader: that needs a
    // Curator's review, not a merge rule); an implicit none_stated/not_reviewed never erases
    // what the template reviewed.
    out[dim] = base !== undefined && COVERAGE_STRENGTH[state] < COVERAGE_STRENGTH[base] ? base : state;
  }
  return out;
}

/**
 * Merges a template into a rule set: the rule set's own rule, attestation or group with the
 * same id overrides the template's; coverage merges by mergeCoverage. Hash the merged result,
 * never the unmerged one, or two cycles could share a hash while behaving differently.
 */
export function applyTemplate(template: RuleSetTemplate, ruleSet: EligibilityRuleSet): EligibilityRuleSet {
  if (ruleSet.templateKey !== template.key) throw new RuleSetVersionError(`rule set uses template ${ruleSet.templateKey ?? "none"}, not ${template.key}`);
  return parseRuleSet({
    ...ruleSet,
    coverage: mergeCoverage(template.coverage, ruleSet.coverage),
    rules: overrideById(template.rules, ruleSet.rules),
    anyOf: overrideById(template.anyOf, ruleSet.anyOf),
    attestations: overrideById(template.attestations, ruleSet.attestations),
  });
}

