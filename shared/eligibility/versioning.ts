export type ChangeKind = "added" | "removed" | "changed" | "unchanged";

export interface RuleChange {
  readonly id: string;
  readonly kind: "rule" | "attestation";
  readonly dimension: EligibilityDimension;
  readonly change: ChangeKind;
}

export interface CoverageChange {
  readonly dimension: EligibilityDimension;
  readonly from: Coverage;
  readonly to: Coverage;
}

export interface RuleSetDiff {
  readonly hashChanged: boolean;
  readonly rules: readonly RuleChange[];
  readonly coverage: readonly CoverageChange[];
  /** Dimensions with any added, removed or changed rule, attestation or coverage. */
  readonly dimensions: readonly EligibilityDimension[];
}

function diffById<T extends { id: string; dimension: EligibilityDimension }>(prev: readonly T[], next: readonly T[], kind: RuleChange["kind"]): RuleChange[] {
  const before = new Map(prev.map((x) => [x.id, x]));
  const after = new Map(next.map((x) => [x.id, x]));
  const ids = [...new Set([...before.keys(), ...after.keys()])].sort();
  return ids.map((id) => {
    const a = before.get(id);
    const b = after.get(id);
    const dimension = (b ?? a)!.dimension;
    if (!a) return { id, kind, dimension, change: "added" };
    if (!b) return { id, kind, dimension, change: "removed" };
    return { id, kind, dimension, change: canonicalJson(a) === canonicalJson(b) ? "unchanged" : "changed" };
  });
}

/** Compares two versions (or two cycles) rule by rule, by stable id. */
export function diffRuleSets(prev: EligibilityRuleSet, next: EligibilityRuleSet): RuleSetDiff {
  const rules = [...diffById(prev.rules, next.rules, "rule"), ...diffById(prev.attestations, next.attestations, "attestation")];
  const coverage: CoverageChange[] = [];
  for (const dimension of ELIGIBILITY_DIMENSIONS) {
    const from = prev.coverage[dimension] ?? "not_reviewed";
    const to = next.coverage[dimension] ?? "not_reviewed";
    if (from !== to) coverage.push({ dimension, from, to });
  }
  const dims = new Set<EligibilityDimension>([...rules.filter((r) => r.change !== "unchanged").map((r) => r.dimension), ...coverage.map((c) => c.dimension)]);
  return {
    hashChanged: computeRuleSetHash(prev) !== computeRuleSetHash(next),
    rules,
    coverage,
    dimensions: ELIGIBILITY_DIMENSIONS.filter((d) => dims.has(d)),
  };
}

export interface ResultChange {
  readonly changed: boolean;
  readonly verdictChanged: boolean;
  /** Rules (by id) whose verdict changed, appeared or disappeared. */
  readonly ruleIds: readonly string[];
}

/**
 * Whether a student's result changed between two evaluations: the alert rule is "alert only when
 * the result, or a rule the result depends on, changes" (plan 6.4.3).
 */
export function compareResults(prev: EligibilityResult, next: EligibilityResult): ResultChange {
  const before = new Map(prev.rules.map((r) => [r.ruleId, r.verdict]));
  const after = new Map(next.rules.map((r) => [r.ruleId, r.verdict]));
  const ids = [...new Set([...before.keys(), ...after.keys()])].sort();
  const ruleIds = ids.filter((id) => before.get(id) !== after.get(id));
  const verdictChanged = prev.verdict !== next.verdict || prev.status !== next.status;
  return { changed: verdictChanged || ruleIds.length > 0, verdictChanged, ruleIds };
}
