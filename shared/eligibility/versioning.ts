import {
  ELIGIBILITY_DIMENSIONS,
  EligibilityRuleSetSchema,
  type Attestation,
  type Coverage,
  type EligibilityDimension,
  type EligibilityResult,
  type EligibilityRule,
  type EligibilityRuleSet,
  type EligibilityRuleSetInput,
} from "../contracts/eligibility";
import { canonicalJson, sha256Hex } from "./hash";

/**
 * Versioned rule sets. A rule set is keyed by (programCycleId, version) and moves
 * draft -> verified -> superseded. A verified version is immutable: any change is a new draft at
 * version + 1. Rule ids are stable across versions and cycles, so diffs compare rules by id.
 */

/** Semantic version of the evaluator; results computed under another version are recomputed. */
export const ENGINE_VERSION = "1.0.0";

/** The parts of a rule set that decide a result; ids, version, state and quotes are excluded. */
export function hashBody(ruleSet: Pick<EligibilityRuleSet, "format" | "coverage" | "rules" | "anyOf" | "attestations" | "nomination">): unknown {
  return {
    format: ruleSet.format,
    coverage: ruleSet.coverage,
    rules: ruleSet.rules,
    anyOf: ruleSet.anyOf,
    attestations: ruleSet.attestations,
    nomination: ruleSet.nomination,
  };
}

/** sha256 over the canonical JSON of the hash body (template already merged in). */
export function computeRuleSetHash(ruleSet: Parameters<typeof hashBody>[0]): string {
  return sha256Hex(canonicalJson(hashBody(ruleSet)));
}

export class RuleSetVersionError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "RuleSetVersionError";
  }
}

/** Validates and normalizes input (zod defaults applied), throwing on any contract issue. */
export function parseRuleSet(input: EligibilityRuleSetInput | unknown): EligibilityRuleSet {
  return EligibilityRuleSetSchema.parse(input);
}

/** Marks a draft verified: computes the hash and records who verified it and when. */
export function verifyRuleSet(draft: EligibilityRuleSet, by: { verifiedBy: string; verifiedAt: string }): EligibilityRuleSet {
  if (draft.state !== "draft") throw new RuleSetVersionError(`only drafts can be verified (state ${draft.state})`);
  return parseRuleSet({ ...draft, state: "verified", hash: computeRuleSetHash(draft), verifiedBy: by.verifiedBy, verifiedAt: by.verifiedAt });
}

export function supersedeRuleSet(ruleSet: EligibilityRuleSet): EligibilityRuleSet {
  if (ruleSet.state !== "verified") throw new RuleSetVersionError("only verified rule sets are superseded");
  return { ...ruleSet, state: "superseded" };
}

/** True when a stored hash matches the content (verified rows must always pass). */
export function hashMatches(ruleSet: EligibilityRuleSet): boolean {
  return ruleSet.hash !== null && ruleSet.hash === computeRuleSetHash(ruleSet);
}

/**
 * Starts the next version from a verified or superseded one. The caller supplies the new id
 * (ids are generated by the database layer, not here, to keep this module pure).
 */
export function reviseRuleSet(
  previous: EligibilityRuleSet,
  next: { id: string; changes?: Partial<Pick<EligibilityRuleSet, "coverage" | "rules" | "anyOf" | "attestations" | "nomination" | "evidence">> },
): EligibilityRuleSet {
  if (previous.state === "draft") throw new RuleSetVersionError("revise a verified version; edit the draft in place instead");
  return parseRuleSet({
    ...previous,
    ...next.changes,
    id: next.id,
    version: previous.version + 1,
    state: "draft",
    hash: null,
    verifiedAt: null,
    verifiedBy: null,
  });
}

/**
 * Guards the write path: a verified (or superseded) version may never change content. Returns
 * normally when `incoming` is a new version, or the same version with identical content.
 */
export function assertImmutable(stored: EligibilityRuleSet, incoming: EligibilityRuleSet): void {
  if (stored.programCycleId !== incoming.programCycleId || stored.version !== incoming.version) return;
  if (stored.state === "draft") return;
  if (computeRuleSetHash(stored) !== computeRuleSetHash(incoming)) {
    throw new RuleSetVersionError(`version ${stored.version} is ${stored.state} and immutable; write version ${stored.version + 1}`);
  }
}

/** The rule set to evaluate for a cycle: the highest verified version, else null. */
export function currentRuleSet(ruleSets: readonly EligibilityRuleSet[], programCycleId: string): EligibilityRuleSet | null {
  const verified = ruleSets.filter((r) => r.programCycleId === programCycleId && r.state === "verified");
  return verified.reduce<EligibilityRuleSet | null>((best, r) => (best === null || r.version > best.version ? r : best), null);
}

/** True when a stored or cached result was computed from a different rule set or engine. */
export function isResultStale(result: Pick<EligibilityResult, "ruleSet">, ruleSet: EligibilityRuleSet | null, engineVersion: string, currentEngine = ENGINE_VERSION): boolean {
  if (engineVersion !== currentEngine) return true;
  if (!ruleSet || !result.ruleSet) return (ruleSet === null) !== (result.ruleSet === null);
  return result.ruleSet.id !== ruleSet.id || result.ruleSet.version !== ruleSet.version || result.ruleSet.hash !== ruleSet.hash;
}

