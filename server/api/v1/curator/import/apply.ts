import { getDb, type Db } from "../../../../db/client";
import { registryAuditInsert } from "../../../../db/repos/audit";
import { isUniqueViolation, runBatch, type Stmt } from "../../../../db/repos/common";
import * as s from "../../../../db/schema";
import { renderStatements, type BuiltQuery } from "../../../../db/seed/sql";
import type { ImportPlan, PlannedUnit } from "./plan";

/**
 * Writes a plan. The new Organizations go first in one batch; then each created row is its own
 * D1 batch (Program, types, host row, Source, ExternalRef, ReviewTasks, registry_audit), so a
 * row that lost a race (its slug or id taken a moment ago) fails alone and is reported, while the
 * rest commit. Host rows and Sources use ON CONFLICT DO NOTHING: an import never loosens a host
 * policy a Curator set, and never relinks a Source.
 */

export function organizationStatements(db: Db, plan: ImportPlan): Stmt[] {
  const out: Stmt[] = [];
  for (const o of plan.organizations) {
    out.push(db.insert(s.organizations).values(o.row));
    out.push(registryAuditInsert(db, o.audit));
  }
  return out;
}

export function unitStatements(db: Db, unit: PlannedUnit): Stmt[] {
  const out: Stmt[] = [db.insert(s.programs).values(unit.program)];
  if (unit.types.length) out.push(db.insert(s.programTypes).values(unit.types));
  if (unit.host) out.push(db.insert(s.sourceHosts).values(unit.host).onConflictDoNothing());
  if (unit.source) out.push(db.insert(s.sources).values(unit.source).onConflictDoNothing());
  out.push(db.insert(s.externalRefs).values(unit.externalRef));
  for (const t of unit.tasks) out.push(db.insert(s.reviewTasks).values(t));
  for (const a of unit.audits) out.push(registryAuditInsert(db, a));
  return out;
}

/** Applies the plan to D1; failed rows are marked `failed` in `plan.outcomes` (mutated). */
export async function applyPlan(db: Db, plan: ImportPlan): Promise<ImportPlan> {
  await runBatch(db, organizationStatements(db, plan));
  for (const unit of plan.units) {
    try {
      await runBatch(db, unitStatements(db, unit));
    } catch (err) {
      if (!isUniqueViolation(err)) throw err;
      const outcome = plan.outcomes.find((o) => o.row === unit.row);
      if (outcome) {
        outcome.status = "failed";
        outcome.errors = [{ path: "(row)", message: "The registry changed during the import (a slug or link was taken). Run the import again." }];
        delete outcome.programId;
        delete outcome.taskIds;
      }
    }
  }
  return plan;
}

/** A Drizzle client used only to render SQL; it never executes anything. */
function renderer(): Db {
  return getDb({} as D1Database);
}

/**
 * The plan as self-contained SQL for `wrangler d1 execute --local --file` (the CLI). Built with
 * the same statements as `applyPlan`, so both paths write the same rows.
 */
export function renderPlanSql(plan: ImportPlan): string {
  const db = renderer();
  const queries: BuiltQuery[] = [];
  const add = (stmts: Stmt[]) => {
    for (const st of stmts) {
      const q = (st as unknown as { toSQL(): { sql: string; params: unknown[] } }).toSQL();
      queries.push({ sql: q.sql, params: q.params });
    }
  };
  add(organizationStatements(db, plan));
  for (const unit of plan.units) add(unitStatements(db, unit));
  const header = [
    `-- Novus candidate import ${plan.batchId} (${plan.format}, file sha256 ${plan.fileSha256.slice(0, 16)}).`,
    "-- Draft programs only: is_published = 0, no cycles, no verified facts; every row has a Curator ReviewTask.",
    "-- Generated by infra/scripts/import-candidates.ts for the LOCAL D1. Do not commit this file.",
  ].join("\n");
  return queries.length ? `${header}\n${renderStatements(queries)}` : `${header}\n`;
}
