import {
  CYCLE_MODELS,
  CYCLE_STATUSES,
  DEADLINE_KINDS,
  LIFECYCLES,
  OPPORTUNITY_TYPES,
  REVIEW_TASK_KINDS,
} from "../../../shared/taxonomy";
import { sqlLiteral } from "./sql";

/**
 * Lookup rows for growing enums (data model 3.2, rule 2), generated from shared/taxonomy so the
 * database and the zod enums cannot drift. These are production rows, not sample data, so they
 * ship as a migration; `lookups.test.ts` checks the committed migration equals this output.
 */

export function humanize(code: string): string {
  const words = code.replace(/[_.]+/g, " ").trim();
  return words.charAt(0).toUpperCase() + words.slice(1);
}

function lookupInserts(table: string, codes: readonly string[]): string[] {
  return codes.map(
    (code, i) => `INSERT OR IGNORE INTO ${table} (code, label, sort_order) VALUES (${sqlLiteral(code)}, ${sqlLiteral(humanize(code))}, ${i});`,
  );
}

export function lookupStatements(): string[] {
  const types = OPPORTUNITY_TYPES.map(
    (t) =>
      `INSERT OR IGNORE INTO opportunity_types (slug, ordinal, label, group_key, in_scope) VALUES (${sqlLiteral(t.slug)}, ${t.ordinal}, ${sqlLiteral(t.label)}, ${sqlLiteral(t.group)}, ${t.inScope ? 1 : 0});`,
  );
  return [
    ...types,
    ...lookupInserts("lifecycles", LIFECYCLES),
    ...lookupInserts("cycle_statuses", CYCLE_STATUSES),
    ...lookupInserts("cycle_models", CYCLE_MODELS),
    ...lookupInserts("deadline_kinds", DEADLINE_KINDS),
    ...lookupInserts("review_task_kinds", REVIEW_TASK_KINDS),
  ];
}

export function renderLookupsSql(): string {
  const header = "-- Lookup rows: generated by server/db/seed/lookups.ts (renderLookupsSql) from shared/taxonomy.\n";
  return header + lookupStatements().join("\n--> statement-breakpoint\n") + "\n";
}
