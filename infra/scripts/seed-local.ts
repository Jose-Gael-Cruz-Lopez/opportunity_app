/**
 * Seeds the LOCAL D1 database (`novus-main`) with SAMPLE data for development and demos.
 *
 *   npm run db:seed:local -- [--today 2026-11-11] [--reset] [--migrate] [--dry-run]
 *   node --experimental-strip-types infra/scripts/seed-local.ts [flags]
 *
 * Flags:
 *   --today YYYY-MM-DD  anchor date for every sample date (default 2026-11-11)
 *   --reset             delete the sample rows (and local rows pointing at them) first
 *   --migrate           apply migrations to the local database first
 *   --dry-run           write the SQL file and print its path; do not touch D1
 *   --config PATH       wrangler config (default infra/wrangler/wrangler.toml)
 *   --database NAME     D1 database name (default novus-main)
 *
 * Every program, organization, date and rule it inserts is invented and stored with
 * is_sample = 1. It only ever runs `wrangler d1 execute --local`; there is no remote mode.
 *
 * This file uses only Node built-ins so it runs under `--experimental-strip-types`; the SQL is
 * generated by server/db/seed/cli.ts through tsx, which resolves the repository's imports.
 */
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..");

interface Options {
  today: string | null;
  reset: boolean;
  migrate: boolean;
  dryRun: boolean;
  config: string;
  database: string;
}

function parseArgs(argv: readonly string[]): Options {
  const value = (name: string): string | null => {
    const i = argv.indexOf(name);
    if (i < 0) return null;
    const v = argv[i + 1];
    if (!v || v.startsWith("--")) throw new Error(`${name} needs a value`);
    return v;
  };
  const today = value("--today");
  if (today !== null && !/^\d{4}-\d{2}-\d{2}$/.test(today)) throw new Error("--today must be YYYY-MM-DD");
  const database = value("--database") ?? "novus-main";
  if (!/^[a-z0-9-]+$/.test(database)) throw new Error("--database must be a plain D1 name");
  return {
    today,
    reset: argv.includes("--reset"),
    migrate: argv.includes("--migrate"),
    dryRun: argv.includes("--dry-run"),
    config: value("--config") ?? "infra/wrangler/wrangler.toml",
    database,
  };
}

/** Runs a command with arguments (no shell), streaming its output; throws on failure. */
function run(command: string, args: readonly string[], capture = false): string {
  const result = spawnSync(command, args, {
    cwd: ROOT,
    encoding: "utf8",
    stdio: capture ? ["ignore", "pipe", "inherit"] : "inherit",
    maxBuffer: 64 * 1024 * 1024,
  });
  if (result.error) throw result.error;
  if (result.status !== 0) throw new Error(`${command} ${args.join(" ")} exited with ${result.status}`);
  return capture ? result.stdout : "";
}

function main(): void {
  const opts = parseArgs(process.argv.slice(2));
  const cliArgs = ["tsx", "server/db/seed/cli.ts", "sample"];
  if (opts.today) cliArgs.push("--today", opts.today);
  if (opts.reset) cliArgs.push("--reset");
  const sql = run("npx", cliArgs, true);

  // .wrangler/ is gitignored, so the generated file never lands in the public repository.
  const outDir = join(ROOT, ".wrangler", "novus-seed");
  mkdirSync(outDir, { recursive: true });
  const file = join(outDir, "sample-seed.sql");
  writeFileSync(file, sql, "utf8");
  console.log(`Wrote ${sql.split("\n").length} lines of SAMPLE seed SQL to ${file}`);
  if (opts.dryRun) return;

  if (opts.migrate) {
    run("npx", ["wrangler", "d1", "migrations", "apply", opts.database, "--local", "--config", opts.config]);
  }
  run("npx", ["wrangler", "d1", "execute", opts.database, "--local", "--config", opts.config, "--file", file, "--yes"]);
  console.log("Local D1 seeded with SAMPLE data (is_sample = 1). Nothing here describes a real program.");
}

try {
  main();
} catch (err) {
  console.error(err instanceof Error ? err.message : String(err));
  process.exitCode = 1;
}
